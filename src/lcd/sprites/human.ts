/**
 * The person on the screen: Ömer — computer-engineering student, AI engineer.
 * An original 1-bit figure, not a mascot: a cap of dark hair, a light face with
 * two eye pixels, a hoodie body, 1px arms and 2px legs with feet.
 *
 * Two sizes, both anchored at the TOP-LEFT of their canvas:
 *   BIG   16x18 — the main stage (idle, menu, boot, every mood script).
 *                 Standing poses plant their feet on row 17, so a pose can be
 *                 swapped for another without moving the blit position.
 *   MINI  12x16 — the 16px strip of a section screen (and the `adult` stage of
 *                 the journey). Same character, one head row and one torso row
 *                 shorter. Feet on row 15.
 *
 * Breathing is built into the art, not into the blit offset: the *_B frames
 * drop the head and shoulders by 1px while the feet stay planted, so the figure
 * never looks like it is hopping in place.
 */

